/* ---------- 拖入文档 → 自动识别表格 → 生成模板 ---------- */
function u8ToText(u){ return new TextDecoder().decode(u); }
async function unzip(buf){
  const dv=new DataView(buf); let eocd=-1;
  for(let i=buf.byteLength-22;i>=Math.max(0,buf.byteLength-66000);i--){
    if(dv.getUint32(i,true)===0x06054b50){ eocd=i; break; }
  }
  if(eocd<0) throw new Error('不是 zip 格式');
  const n=dv.getUint16(eocd+10,true); let off=dv.getUint32(eocd+16,true);
  const out={};
  for(let k=0;k<n;k++){
    if(dv.getUint32(off,true)!==0x02014b50) break;
    const method=dv.getUint16(off+10,true), csize=dv.getUint32(off+20,true);
    const nlen=dv.getUint16(off+28,true), elen=dv.getUint16(off+30,true), clen=dv.getUint16(off+32,true);
    const lho=dv.getUint32(off+42,true);
    const name=u8ToText(new Uint8Array(buf,off+46,nlen));
    const lnlen=dv.getUint16(lho+26,true), lelen=dv.getUint16(lho+28,true);
    out[name]={method, data:new Uint8Array(buf, lho+30+lnlen+lelen, csize)};
    off+=46+nlen+elen+clen;
  }
  return out;
}
async function entryText(f){
  if(!f) return '';
  if(f.method===0) return u8ToText(f.data);
  const st=new Blob([f.data]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
  return u8ToText(new Uint8Array(await new Response(st).arrayBuffer()));
}
async function tablesFromDocx(buf){
  const z=await unzip(buf);
  const xml=await entryText(z['word/document.xml']);
  if(!xml) throw new Error('没有读到 word/document.xml');
  const doc=new DOMParser().parseFromString(xml,'application/xml');
  return [...doc.getElementsByTagNameNS('*','tbl')].map(tb=>
    [...tb.children].filter(r=>r.localName==='tr').map(tr=>
      [...tr.children].filter(c=>c.localName==='tc').map(tc=>
        [...tc.getElementsByTagNameNS('*','t')].map(t=>t.textContent).join('').trim()
      )
    )
  );
}
async function tablesFromXlsx(buf){
  const z=await unzip(buf);
  const ssxml=await entryText(z['xl/sharedStrings.xml']);
  let strs=[];
  if(ssxml){
    const sd=new DOMParser().parseFromString(ssxml,'application/xml');
    strs=[...sd.getElementsByTagNameNS('*','si')].map(si=>[...si.getElementsByTagNameNS('*','t')].map(t=>t.textContent).join(''));
  }
  let sheet='';
  for(const k in z){ if(/^xl\/worksheets\/sheet\d+\.xml$/.test(k)){ sheet=await entryText(z[k]); break; } }
  if(!sheet) throw new Error('没有读到工作表');
  const doc=new DOMParser().parseFromString(sheet,'application/xml');
  const rows=[...doc.getElementsByTagNameNS('*','row')].map(r=>{
    const cells=[...r.children].filter(c=>c.localName==='c').map(c=>{
      const t=c.getAttribute('t');
      const v=c.getElementsByTagNameNS('*','v')[0];
      if(t==='s'&&v) return (strs[+v.textContent]||'').trim();
      if(t==='inlineStr'){ const is=c.getElementsByTagNameNS('*','t')[0]; return is?is.textContent.trim():''; }
      return v?v.textContent.trim():'';
    });
    return cells;
  });
  return [rows];
}
function tablesFromText(txt){
  const lines=txt.split(/\r?\n/).filter(l=>l.trim());
  const pick=(l)=>{ if(l.indexOf('\t')>=0) return l.split('\t'); if(l.indexOf('|')>=0) return l.split('|'); if(l.indexOf(',')>=0) return l.split(','); return l.split(/\s{2,}|\s/); };
  return [lines.map(l=>pick(l).map(s=>s.trim()).filter((s,i,a)=>!(s===''&&i===a.length-1)))];
}
async function parseDoc(file){
  const buf=await file.arrayBuffer();
  const nm=file.name.toLowerCase();
  let tabs=[];
  if(nm.endsWith('.docx')) tabs=await tablesFromDocx(buf);
  else if(nm.endsWith('.xlsx')) tabs=await tablesFromXlsx(buf);
  else if(nm.endsWith('.doc')) throw new Error('老版 .doc 读不了，请另存为 .docx');
  else tabs=tablesFromText(u8ToText(new Uint8Array(buf)));
  tabs=tabs.filter(t=>t && t.length && t.some(r=>r.length>=2));
  if(!tabs.length) throw new Error('这份文件里没有找到表格');
  tabs.sort((a,b)=>b.length*a[0].length-a.length*b[0].length);
  return tabs[0];
}
function normTable(rows){
  const head=rows[0].map(s=>s.replace(/\s+/g,' ').trim());
  const body=rows.slice(1,6).map(r=>r.map(s=>s.replace(/\s+/g,' ').trim()));
  return {cols:head.filter(Boolean).slice(0,8), rows:body};
}
let pendingTpl=null;
function showParsed(file, rows){
  const t=normTable(rows);
  if(!t.cols.length){ toast('表格第一行是空的，读不出列名'); return; }
  pendingTpl={id:'tpl'+(TPLS.length+1), name:file.name.replace(/\.[^.]+$/,'')+'模板', style:'std', cols:t.cols};
  const prev='<table style="width:100%;border-collapse:collapse;font-size:12px"><tr>'+t.cols.map(c=>'<th>'+c+'</th>').join('')+'</tr>'
    + t.rows.map(r=>'<tr>'+t.cols.map((c,i)=>'<td style="height:26px;color:#5a6b7d">'+(r[i]||'')+'</td>').join('')+'</tr>').join('')+'</table>';
  $('#dropPrev').innerHTML='<div style="margin-top:14px">'
    +'<div class="hint">识别结果（来自 '+file.name+'）：</div>'
    +'<div class="tpl-prev" style="margin-top:8px">'+prev+'</div>'
    +'<div class="grid2"><div class="f"><label>模板名称</label><input id="p-name" value="'+pendingTpl.name+'"></div>'
    +'<div class="f"><label>列名（用 / 分隔）</label><input id="p-cols" value="'+t.cols.join('/')+'"></div></div>'
    +'<button class="btn" id="p-save">保存为模板</button> '
    +'<button class="btn ghost" id="p-cancel">取消</button></div>';
  $('#p-save').onclick=()=>{
    const nm=$('#p-name').value.trim()||pendingTpl.name;
    const cols=$('#p-cols').value.split('/').map(s=>s.trim()).filter(Boolean);
    if(!cols.length){ toast('列名不能为空'); return; }
    pendingTpl.name=nm; pendingTpl.cols=cols;
    if(TPLS.some(x=>x.id===pendingTpl.id)) pendingTpl.id='tpl'+Date.now().toString(36);
    TPLS.push(pendingTpl); save(); renderAll();
    $('#dropPrev').innerHTML=''; pendingTpl=null; toast('模板已保存');
  };
  $('#p-cancel').onclick=()=>{ $('#dropPrev').innerHTML=''; pendingTpl=null; };
}
async function handleFile(file){
  if(!file) return;
  try{ const rows=await parseDoc(file); showParsed(file, rows); }
  catch(e){ toast('识别失败：'+e.message); }
}

